/* system/kversion.c — いま走っているカーネルの版。
 *
 * ★ この一ファイルだけは毎回コンパイルし直す（Makefile の FORCE 依存）。
 *   そうしないと __DATE__ / __TIME__ が古いままになり、版を名乗る意味が消える。
 *
 * なぜ要るか: 焼いたあと「HTTP が応答した」ことを「再起動した」と取り違えて、
 * 古いカーネルに向かって実験を続けたことがある。板が生きていることと、
 * 焼いたものが走っていることは別である。GET /version で必ず突き合わせること。
 */
const char *kernel_build_id(void) { return __DATE__ " " __TIME__; }
